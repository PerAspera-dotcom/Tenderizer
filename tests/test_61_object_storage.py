def test_presign_then_confirm_vault_upload(tmp_path, monkeypatch, s3):
    _seed(tmp_path, monkeypatch)
    monkeypatch.setattr(api, "_run_vault_processing", lambda *a, **k: None)
    out = api.presign_upload(api.UploadPresignBody(area="vault", filename="sheet.pdf",
                                                   content_type="application/pdf"),
                             tenant_id=TEST_TENANT_ID)
    assert out["mode"] == "s3" and out["object_key"].startswith(f"{TEST_TENANT_ID}/vault/_/")
    s3.objects[out["object_key"]] = b"%PDF uploaded by the browser"  # the browser's direct POST

    created = asyncio.run(api.ingest_vault_document(
        BackgroundTasks(), file=None, object_key=out["object_key"], filename="sheet.pdf",
        content_type="application/pdf", tenant_id=TEST_TENANT_ID))
    doc = store.get_vault_document(api._db(), TEST_TENANT_ID, created["id"])
    assert doc["object_key"] == out["object_key"] and doc["storage_path"] == ""
    assert created["filename"] == "sheet.pdf"


