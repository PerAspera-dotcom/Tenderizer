def test_filesystem_fallback_round_trip_when_bucket_unset():
    assert object_storage.configured() is False
    key = object_storage.new_key(1, "vault", "a.pdf")
    object_storage.put(key, b"hello")
    assert object_storage.get(key) == b"hello"
    assert object_storage.size(key) == 5
    assert object_storage.presigned_get(key) is None
    assert object_storage.presigned_post(key) is None
    with object_storage.local_copy(key) as path:
        assert open(path, "rb").read() == b"hello"
    object_storage.delete(key)
    assert not object_storage.exists(key)
    object_storage.delete(key)  # idempotent


