class FakeS3:
    """Just the S3 calls object_storage makes."""

    def __init__(self):
        self.objects = {}
        self._signer = boto3.client("s3", region_name="eu-central-1", aws_access_key_id="AKIATEST",
                                    aws_secret_access_key="secret")

    @staticmethod
    def _missing(op):
        return ClientError({"Error": {"Code": "404" if op == "HeadObject" else "NoSuchKey"}}, op)

    def put_object(self, Bucket, Key, Body, **kw):
        self.objects[Key] = Body

    def upload_file(self, filename, bucket, key, ExtraArgs=None):
        with open(filename, "rb") as f:
            self.objects[key] = f.read()

    def get_object(self, Bucket, Key):
        if Key not in self.objects:
            raise self._missing("GetObject")
        return {"Body": io.BytesIO(self.objects[Key])}

    def head_object(self, Bucket, Key):
        if Key not in self.objects:
            raise self._missing("HeadObject")
        return {"ContentLength": len(self.objects[Key])}

    def delete_object(self, Bucket, Key):
        self.objects.pop(Key, None)

    def list_objects_v2(self, Bucket, Prefix="", **kw):
        return {"Contents": [{"Key": k} for k in self.objects if k.startswith(Prefix)]}

    def generate_presigned_url(self, *a, **kw):
        return self._signer.generate_presigned_url(*a, **kw)

    def generate_presigned_post(self, *a, **kw):
        return self._signer.generate_presigned_post(*a, **kw)


