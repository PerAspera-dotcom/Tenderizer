def test_upload_window_outlives_a_slow_100mb_transfer_while_downloads_stay_short(s3):
    import base64
    from datetime import datetime, timezone
    assert object_storage.DOWNLOAD_URL_TTL_SECONDS == 300
    assert object_storage.UPLOAD_URL_TTL_SECONDS >= 1800
    post = object_storage.presigned_post(object_storage.new_key(1, "vault", "a.pdf"))
    expiry = json.loads(base64.b64decode(post["fields"]["policy"]))["expiration"]
    remaining = datetime.fromisoformat(expiry.replace("Z", "+00:00")) - datetime.now(timezone.utc)
    assert remaining.total_seconds() > 29 * 60


def test_migrate_never_deletes_any_local_original(tmp_path, monkeypatch, s3):
    import storage_migration
    out_dir = tmp_path / "composer_output"
    monkeypatch.setattr(storage_migration, "COMPOSER_OUTPUT_DIR", out_dir)
    conn = _seed(tmp_path, monkeypatch)
    originals = []
    legacy_doc = tmp_path / "uploads" / "1" / "P-1" / "a.pdf"
    legacy_doc.parent.mkdir(parents=True)
    legacy_doc.write_bytes(b"doc")
    store.add_document(conn, TEST_TENANT_ID, "P-1", "a.pdf", "application/pdf", 3, str(legacy_doc))
    originals.append(legacy_doc)
    keyed = object_storage.new_key(TEST_TENANT_ID, "vault", "b.pdf")
    object_storage.local_path(keyed).parent.mkdir(parents=True, exist_ok=True)
    object_storage.local_path(keyed).write_bytes(b"vault")
    store.add_vault_document(conn, TEST_TENANT_ID, "b.pdf", "application/pdf", 5, "", object_key=keyed)
    originals.append(object_storage.local_path(keyed))
    output = out_dir / "1" / "P-1" / "gaps_report.txt"
    output.parent.mkdir(parents=True)
    output.write_text("gaps")
    originals.append(output)
    legacy_tr = object_storage.local_path("documents/1/abc/original.pdf")
    legacy_tr.parent.mkdir(parents=True)
    legacy_tr.write_bytes(b"sow")
    store.create_translated_document(conn, TEST_TENANT_ID, "sow.pdf", "application/pdf", 3,
                                     "documents/1/abc/original.pdf", "h", "FR", "EN", "d", "k", "me")
    originals.append(legacy_tr)

    storage_migration.migrate(conn, dry_run=False, log=lambda *_: None)
    storage_migration.migrate(conn, dry_run=False, log=lambda *_: None)
    assert all(p.is_file() for p in originals)
    assert len(s3.objects) == 4
