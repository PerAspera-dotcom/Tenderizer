def test_s3_mode_put_get_delete(s3):
    key = object_storage.new_key(1, "vault", "a.pdf")
    object_storage.put(key, b"bytes")
    assert s3.objects[key] == b"bytes"
    assert not object_storage.local_path(key).exists()  # nothing written to disk
    assert object_storage.get(key) == b"bytes"
    object_storage.delete(key)
    assert key not in s3.objects


def test_s3_presigned_get_is_short_lived_and_carries_the_filename(s3):
    key = object_storage.new_key(1, "tender_documents", "a.pdf", pub_number="P-1")
    object_storage.put(key, b"x")
    url = object_storage.presigned_get(key, filename="Lastenheft ü.pdf", content_type="application/pdf")
    assert "X-Amz-Signature=" in url and "X-Amz-Expires=300" in url
    assert "response-content-disposition=" in url


def test_s3_presigned_post_enforces_size_in_the_policy(s3):
    key = object_storage.new_key(1, "vault", "a.pdf")
    post = object_storage.presigned_post(key, "application/pdf", max_size=1234)
    policy = json.loads(__import__("base64").b64decode(post["fields"]["policy"]))
    assert ["content-length-range", 1, 1234] in policy["conditions"]
    assert post["fields"]["key"] == key


def test_cutover_fallback_reads_local_copy_when_object_not_yet_in_bucket(s3):
    key = object_storage.new_key(1, "vault", "a.pdf")
    path = object_storage.local_path(key)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(b"still on the volume")
    assert object_storage.get(key) == b"still on the volume"
    assert object_storage.exists(key)
    assert object_storage.presigned_get(key) is None  # caller streams it instead


