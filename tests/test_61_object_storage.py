# ── storage-migrate / storage-restore-local ──────────────────────────────────

class _Paginator:
    def __init__(self, fake):
        self.fake = fake

    def paginate(self, Bucket):
        yield {"Contents": [{"Key": k, "Size": len(v)} for k, v in self.fake.objects.items()]}


def _with_paginator(fake):
    fake.get_paginator = lambda name: _Paginator(fake)
    return fake


def test_migrate_dry_run_writes_nothing_then_real_run_copies_and_keys(tmp_path, monkeypatch, s3):
    import storage_migration
    monkeypatch.setattr(storage_migration, "COMPOSER_OUTPUT_DIR", tmp_path / "composer_output")
    conn = _seed(tmp_path, monkeypatch)
    legacy = tmp_path / "vault_uploads" / "1" / "abc.pdf"
    legacy.parent.mkdir(parents=True)
    legacy.write_bytes(b"datasheet")
    doc_id = store.add_vault_document(conn, TEST_TENANT_ID, "sheet.pdf", "application/pdf", 9, str(legacy))
    gone_id = store.add_vault_document(conn, TEST_TENANT_ID, "lost.pdf", "application/pdf", 9,
                                       str(tmp_path / "vault_uploads" / "1" / "lost.pdf"))

    stats, missing = storage_migration.migrate(conn, dry_run=True, log=lambda *_: None)
    assert stats["vault_documents:copied_and_keyed"] == 1 and s3.objects == {}
    assert store.get_vault_document(conn, TEST_TENANT_ID, doc_id)["object_key"] is None

    stats, missing = storage_migration.migrate(conn, dry_run=False, log=lambda *_: None)
    row = store.get_vault_document(conn, TEST_TENANT_ID, doc_id)
    assert row["object_key"].startswith(f"{TEST_TENANT_ID}/vault/_/")
    assert s3.objects[row["object_key"]] == b"datasheet"
    assert row["storage_path"] == str(legacy) and legacy.exists()  # reversible: nothing removed
    assert ("vault_documents", gone_id, str(tmp_path / "vault_uploads" / "1" / "lost.pdf")) in missing

    stats, _ = storage_migration.migrate(conn, dry_run=False, log=lambda *_: None)
    assert stats["vault_documents:already_in_bucket"] == 1  # idempotent


